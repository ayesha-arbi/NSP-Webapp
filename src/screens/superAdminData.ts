export type HubStatus = "on-track" | "behind" | "critical"
export type MintStatus = "queued" | "minting" | "confirmed" | "failed"
export type UserRole = "super-admin" | "center-superintendent" | "trade-tester" | "system"
export type DeviceStatus = "online" | "offline" | "degraded"
export type AuditCategory = "auth" | "approval" | "mint" | "credential" | "device" | "admin" | "assessment"

export interface Hub {
  id: string
  name: string
  enrolled: number
  target: number
  submitted: number
  pendingApproval: number
  minted: number
  status: HubStatus
}

export interface MintTx {
  id: string
  credId: string
  assessId: string
  candidate: string
  hub: string
  status: MintStatus
  retryCount: number
  failReason?: string
  txHash?: string
  lastUpdated: string
  submittedAt: string
}

export interface DeviceHub {
  hubId: string
  hubName: string
  deviceStatus: DeviceStatus
  connectivity: string
  lastConnected: string
  deviceHealth: "good" | "degraded" | "critical"
  edrStatus: "active" | "inactive" | "warning"
  lastSync: string
  offlineRecords: number
}

export interface AuditEntry {
  id: string
  action: string
  user: string
  hub: string
  timestamp: string
  result: "success" | "failure" | "warning"
  category: AuditCategory
  detail?: string
}

export interface FullAuditEntry {
  id: string
  timestamp: string
  eventType: string
  category: AuditCategory
  user: string
  userRole: UserRole
  hub: string
  targetId?: string
  targetType?: "credential" | "assessment" | "user" | "session" | "device"
  ip?: string
  device?: string
  result: "success" | "failure" | "warning"
  detail: string
  metadata?: Record<string, string>
}

