import { useState } from "react"

import type { VerificationResult, VerificationStatus } from "../App"

import NavBar from "../components/NavBar"

import Footer from "../components/Footer"

import StatusPill from "../components/StatusPill"

import { BtnPrimary, BtnSecondary } from "../components/Btn"

interface Props {
  result: VerificationResult

  onVerifyAnother: () => void
}

const CFG: Record<VerificationStatus, {
  accentColor: string
  headerText: string
  body: string
}> = {
  verified: {
    accentColor: "#4C7A6E",

    headerText: "This credential is valid",

    body: "The credential matches the blockchain record and is currently active.",
  },

  tampered: {
    accentColor: "#B08D46",

    headerText: "This credential could not be verified",

    body: "The credential hash does not match the blockchain record. It may have been altered after issuance.",
  },

  revoked: {
    accentColor: "#A6453D",

    headerText: "This credential has been revoked",

    body: "This credential was withdrawn by the issuing authority and is no longer valid.",
  },
}

export default function VerificationResultScreen({
  result,
  onVerifyAnother,
}: Props) {
  const [copied, setCopied] = useState(false)

  const [shared, setShared] = useState(false)

  const cfg = CFG[result.status]

  const isVerified = result.status === "verified"

  const reportLines = [
    "NSP VERIFICATION REPORT",

    "NSP HUNAR — NADRA, Pakistan",

    "=".repeat(48),

    "",

    `Credential ID   : ${result.credentialId}`,

    `Worker          : ${result.workerName ?? "N/A"}`,

    `Skill / Trade   : ${result.skill ?? "N/A"}`,

    `Assessment      : ${result.grade ?? "N/A"}`,

    `Issue Date      : ${result.issueDate ?? "N/A"}`,

    `Testing Centre  : ${result.centre ?? "N/A"}`,

    "",

    `Verification    : ${result.status.toUpperCase()}`,

    `Verified At     : ${result.timestamp}`,

    `On-Chain Ref    : ${result.txHash ?? "N/A"}`,

    `Ledger          : NADRA Blockchain Ledger`,

    "",

    "=".repeat(48),

    "This report was generated by the NSP Verifier Portal.",

    "Do not accept credentials that show TAMPERED or REVOKED status.",
  ]

  const copyToClipboard = (text: string, onSuccess: () => void) => {
    try {
      const ta = document.createElement("textarea")

      ta.value = text

      ta.style.cssText = "position:fixed;top:-9999px;left:-9999px;opacity:0"

      document.body.appendChild(ta)

      ta.focus()

      ta.select()

      document.execCommand("copy")

      document.body.removeChild(ta)

      onSuccess()
    } catch {}
  }

  const handleCopy = () => {
    copyToClipboard(reportLines.join("\n"), () => {
      setCopied(true)

      setTimeout(() => setCopied(false), 2400)
    })
  }

  const handlePrint = () => window.print()

  const handleShare = () => {
    const text = reportLines.join("\n")

    if (navigator.share) {
      navigator
        .share({ title: `NSP Verification — ${result.credentialId}`, text })
        .catch(() => null)
    } else {
      copyToClipboard(text, () => {
        setShared(true)

        setTimeout(() => setShared(false), 2400)
      })
    }
  }

  const handleDownload = () => {
    const blob = new Blob([reportLines.join("\n")], { type: "text/plain" })

    const url = URL.createObjectURL(blob)

    const a = document.createElement("a")

    a.href = url

    a.download = `NSP-Verification-${result.credentialId}-${Date.now()}.txt`

    a.click()

    URL.revokeObjectURL(url)
  }

  return (
    <div
      style={{
        minHeight: "100vh",
        display: "flex",
        flexDirection: "column",
        background: "#F1F0EA",
      }}
    >
      <NavBar
        breadcrumbs={[
          { label: "Verify a Credential", onClick: onVerifyAnother },

          { label: "Result" },
        ]}
      />

      <div style={{ background: "#24302E", padding: "40px 32px 48px" }}>
        <div style={{ maxWidth: 1100, margin: "0 auto" }}>
          <div style={{ display: "flex", alignItems: "flex-start", gap: 24 }}>
            <div
              style={{
                width: 64,
                height: 64,
                borderRadius: 8,
                flexShrink: 0,

                background: `${cfg.accentColor}18`,

                border: `1px solid ${cfg.accentColor}50`,

                display: "flex",
                alignItems: "center",
                justifyContent: "center",
              }}
            >
              {isVerified && (
                <svg width="28" height="28" viewBox="0 0 28 28" fill="none">
                  <path
                    d="M5 14l6.5 6.5L23 8"
                    stroke="#4C7A6E"
                    strokeWidth="2.4"
                    strokeLinecap="round"
                    strokeLinejoin="round"
                  />
                </svg>
              )}
              {result.status === "tampered" && (
                <svg width="28" height="28" viewBox="0 0 28 28" fill="none">
                  <path
                    d="M14 9v8M14 21v1.5"
                    stroke="#B08D46"
                    strokeWidth="2.4"
                    strokeLinecap="round"
                  />
                </svg>
              )}
              {result.status === "revoked" && (
                <svg width="28" height="28" viewBox="0 0 28 28" fill="none">
                  <path
                    d="M7 7l14 14M21 7L7 21"
                    stroke="#A6453D"
                    strokeWidth="2.4"
                    strokeLinecap="round"
                  />
                </svg>
              )}
            </div>

            <div style={{ flex: 1 }}>
              <p
                style={{
                  color: "#B08D46",
                  fontSize: 11,
                  fontWeight: 700,
                  letterSpacing: "0.1em",
                  textTransform: "uppercase",
                  marginBottom: 10,
                }}
              >
                NSP Credential Verification
              </p>
              <div style={{ marginBottom: 12 }}>
                <StatusPill status={result.status} />
              </div>
              <h1
                style={{
                  color: "#F1F0EA",

                  fontSize: 34,
                  fontWeight: 700,

                  lineHeight: 1.15,
                  marginBottom: 10,
                }}
              >
                {cfg.headerText}
              </h1>
              <p
                style={{
                  color: "rgba(241,240,234,0.5)",
                  fontSize: 14,
                  lineHeight: 1.65,
                  maxWidth: 520,
                }}
              >
                {cfg.body}
              </p>
              <div
                style={{
                  marginTop: 16,
                  display: "inline-flex",
                  alignItems: "center",
                  gap: 10,
                  background: "rgba(241,240,234,0.05)",
                  border: "1px solid rgba(241,240,234,0.1)",
                  borderRadius: 6,
                  padding: "8px 14px",
                }}
              >
                <span
                  style={{
                    fontSize: 11,
                    color: "rgba(241,240,234,0.35)",
                    fontWeight: 600,
                    letterSpacing: "0.06em",
                    textTransform: "uppercase",
                  }}
                >
                  ID
                </span>
                <code
                  style={{
                    fontFamily: "'IBM Plex Mono', monospace",
                    fontSize: 13,
                    fontWeight: 500,
                    color: "rgba(241,240,234,0.75)",
                    letterSpacing: "0.04em",
                  }}
                >
                  {result.credentialId}
                </code>
              </div>
            </div>
          </div>
        </div>
      </div>
      <div style={{ height: 3, background: cfg.accentColor, flexShrink: 0 }} />

      <main style={{ flex: 1, padding: "40px 32px 64px" }}>
        <div
          style={{
            maxWidth: 1100,
            margin: "0 auto",
            display: "grid",
            gridTemplateColumns: "1fr 280px",
            gap: 24,
            alignItems: "start",
          }}
        >
          {/* Detail card */}
          <div
            style={{
              background: "#FFFFFF",
              border: "1px solid #D6D3C6",
              borderRadius: 8,
              overflow: "hidden",
            }}
          >
            <div
              style={{
                padding: "14px 24px",
                background: "#F1F0EA",
                borderBottom: "1px solid #D6D3C6",

                display: "flex",
                alignItems: "center",
                justifyContent: "space-between",
              }}
            >
              <span
                style={{
                  fontSize: 12,
                  fontWeight: 700,
                  color: "#8C897C",
                  letterSpacing: "0.07em",
                  textTransform: "uppercase",
                }}
              >
                Credential details
              </span>
              <code
                style={{
                  fontFamily: "'IBM Plex Mono', monospace",
                  fontSize: 13,
                  fontWeight: 500,

                  color: "#24302E",
                  background: "#FFFFFF",

                  padding: "4px 10px",
                  border: "1px solid #D6D3C6",
                  borderRadius: 4,
                }}
              >
                {result.credentialId}
              </code>
            </div>

            <table style={{ width: "100%", borderCollapse: "collapse" }}>
              <tbody>
                {isVerified && (
                  <>
                    <TR label="Worker name" bold>
                      {result.workerName}
                    </TR>
                    <TR label="Skill / Trade">{result.skill}</TR>
                    <TR label="Assessment result">{result.grade}</TR>
                    <TR label="Issue date">{result.issueDate}</TR>
                    <TR label="Testing centre">{result.centre}</TR>
                    <TR label="Credential status">
                      <StatusPill status="active" />
                    </TR>
                    <TR label="On-chain reference (Polygon Amoy)">
                      <div
                        style={{
                          display: "flex",
                          flexDirection: "column",
                          gap: 4,
                        }}
                      >
                        <code
                          style={{
                            fontFamily: "'IBM Plex Mono', monospace",
                            fontSize: 12,
                            color: "#4C7A6E",
                            wordBreak: "break-all",
                          }}
                        >
                          {result.txHash}
                        </code>
                        {result.txHash?.startsWith("0x") && (
                          <a
                            href={`https://amoy.polygonscan.com/tx/${result.txHash}`}
                            target="_blank"
                            rel="noopener noreferrer"
                            style={{
                              fontSize: 11,
                              color: "#4C7A6E",
                              textDecoration: "underline",
                              display: "inline-flex",
                              alignItems: "center",
                              gap: 4,
                            }}
                          >
                            View on PolygonScan Amoy Explorer →
                          </a>
                        )}
                      </div>
                    </TR>
                  </>
                )}
                {result.status === "tampered" && (
                  <>
                    <TR label="Verification status">
                      <StatusPill status="tampered" />
                    </TR>
                    <TR label="Detail">
                      <span
                        style={{
                          fontSize: 13,
                          color: "#5C5A50",
                          lineHeight: 1.6,
                        }}
                      >
                        The credential hash does not match the record at the
                        time of issuance. Do not accept this credential.
                      </span>
                    </TR>
                  </>
                )}
                {result.status === "revoked" && (
                  <>
                    <TR label="Credential status">
                      <StatusPill status="revoked" />
                    </TR>
                    <TR label="Detail">
                      <span
                        style={{
                          fontSize: 13,
                          color: "#5C5A50",
                          lineHeight: 1.6,
                        }}
                      >
                        This credential was withdrawn by the issuing authority.
                        Contact NADRA for further information.
                      </span>
                    </TR>
                  </>
                )}
                <TR label="Verified at">
                  <span
                    style={{
                      fontFamily: "'IBM Plex Mono', monospace",
                      fontSize: 12,
                      color: "#8C897C",
                    }}
                  >
                    {result.timestamp}
                  </span>
                </TR>
                <TR label="Ledger">
                  <span
                    style={{ fontSize: 13, color: "#24302E", fontWeight: 500 }}
                  >
                    Polygon Amoy Testnet (Smart Contract Direct Verification)
                  </span>
                </TR>
              </tbody>
            </table>
          </div>

          {/* Actions column */}
          <div style={{ display: "flex", flexDirection: "column", gap: 12 }}>
            <BtnPrimary
              onClick={onVerifyAnother}
              style={{ width: "100%", justifyContent: "center" }}
            >
              Verify another credential
            </BtnPrimary>

            {/* Print / Share — 50/50 row */}
            <div style={{ display: "flex", gap: 12 }}>
              <BtnSecondary
                onClick={handlePrint}
                style={{
                  flex: 1,
                  justifyContent: "center",
                  gap: 6,
                  minWidth: 0,
                }}
              >
                <svg width="13" height="13" viewBox="0 0 13 13" fill="none">
                  <rect
                    x="2"
                    y="4"
                    width="9"
                    height="6"
                    rx="1"
                    stroke="currentColor"
                    strokeWidth="1.3"
                    fill="none"
                  />
                  <path
                    d="M4 4V2h5v2"
                    stroke="currentColor"
                    strokeWidth="1.3"
                    strokeLinecap="round"
                  />
                  <path
                    d="M4 9h5M4 7h3"
                    stroke="currentColor"
                    strokeWidth="1.3"
                    strokeLinecap="round"
                  />
                </svg>
                Print
              </BtnSecondary>
              <BtnSecondary
                onClick={handleShare}
                style={{
                  flex: 1,
                  justifyContent: "center",
                  gap: 6,
                  minWidth: 0,
                  background: shared ? "#DCE7E3" : "#FFFFFF",
                  color: shared ? "#2F5C4E" : "#24302E",
                }}
              >
                <svg width="13" height="13" viewBox="0 0 13 13" fill="none">
                  <circle
                    cx="10.5"
                    cy="2.5"
                    r="1.5"
                    stroke="currentColor"
                    strokeWidth="1.3"
                    fill="none"
                  />
                  <circle
                    cx="10.5"
                    cy="10.5"
                    r="1.5"
                    stroke="currentColor"
                    strokeWidth="1.3"
                    fill="none"
                  />
                  <circle
                    cx="2.5"
                    cy="6.5"
                    r="1.5"
                    stroke="currentColor"
                    strokeWidth="1.3"
                    fill="none"
                  />
                  <path
                    d="M4 5.8l5-2.8M4 7.2l5 2.8"
                    stroke="currentColor"
                    strokeWidth="1.3"
                    strokeLinecap="round"
                  />
                </svg>
                {shared ? "Copied" : "Share"}
              </BtnSecondary>
            </div>

            {/* Copy — full width */}
            <BtnSecondary
              onClick={handleCopy}
              style={{
                width: "100%",
                justifyContent: "center",
                gap: 8,
                background: copied ? "#DCE7E3" : "#FFFFFF",
                color: copied ? "#2F5C4E" : "#24302E",
              }}
            >
              {copied ? (
                <svg width="13" height="13" viewBox="0 0 13 13" fill="none">
                  <path
                    d="M2 6.5l3 3 6-6"
                    stroke="#4C7A6E"
                    strokeWidth="1.5"
                    strokeLinecap="round"
                    strokeLinejoin="round"
                  />
                </svg>
              ) : (
                <svg width="13" height="13" viewBox="0 0 13 13" fill="none">
                  <rect
                    x="4"
                    y="1"
                    width="8"
                    height="9"
                    rx="1"
                    stroke="currentColor"
                    strokeWidth="1.3"
                    fill="none"
                  />
                  <path
                    d="M1 4v8h8"
                    stroke="currentColor"
                    strokeWidth="1.3"
                    strokeLinecap="round"
                    strokeLinejoin="round"
                    fill="none"
                  />
                </svg>
              )}
              {copied ? "Copied" : "Copy receipt"}
            </BtnSecondary>

            {/* Download — full width */}
            <BtnSecondary
              onClick={handleDownload}
              style={{ width: "100%", justifyContent: "center", gap: 8 }}
            >
              <svg width="13" height="13" viewBox="0 0 13 13" fill="none">
                <path
                  d="M6.5 1v7M4 6l2.5 2.5L9 6"
                  stroke="currentColor"
                  strokeWidth="1.4"
                  strokeLinecap="round"
                  strokeLinejoin="round"
                />
                <path
                  d="M1.5 10.5h10"
                  stroke="currentColor"
                  strokeWidth="1.4"
                  strokeLinecap="round"
                />
              </svg>
              Download verification report
            </BtnSecondary>

            {/* Context note */}
            <div
              style={{
                background: "#FFFFFF",
                border: "1px solid #D6D3C6",

                borderTop: `3px solid ${cfg.accentColor}`,

                borderRadius: "0 0 8px 8px",
                padding: "16px",
              }}
            >
              <p
                style={{
                  fontSize: 11,
                  fontWeight: 700,
                  color: cfg.accentColor,
                  letterSpacing: "0.06em",
                  textTransform: "uppercase",
                  marginBottom: 8,
                }}
              >
                {isVerified ? "What this means" : "Next steps"}
              </p>
              <p style={{ fontSize: 13, color: "#5C5A50", lineHeight: 1.65 }}>
                {isVerified
                  ? "The credential is genuine and active. You may proceed with employment verification."
                  : "Ask the worker to contact their issuing centre or NADRA if they believe this is an error."}
              </p>
            </div>

            {/* Timestamp */}
            <div
              style={{
                background: "#F1F0EA",
                border: "1px solid #D6D3C6",
                borderRadius: 8,
                padding: "14px 16px",
              }}
            >
              <p
                style={{
                  fontSize: 10,
                  fontWeight: 700,
                  color: "#8C897C",
                  letterSpacing: "0.07em",
                  textTransform: "uppercase",
                  marginBottom: 4,
                }}
              >
                Verified at
              </p>
              <p
                style={{
                  fontFamily: "'IBM Plex Mono', monospace",
                  fontSize: 12,
                  color: "#5C5A50",
                }}
              >
                {result.timestamp}
              </p>
            </div>
          </div>
        </div>
      </main>

      <Footer />
    </div>
  )
}

function TR({
  label,
  children,
  bold,
}: {
  label: string
  children: React.ReactNode
  bold?: boolean
}) {
  return (
    <tr style={{ borderBottom: "1px solid #D6D3C6" }}>
      <th
        style={{
          padding: "14px 16px 14px 24px",
          textAlign: "left",

          fontSize: 13,
          fontWeight: 500,
          color: "#8C897C",

          width: 180,
          verticalAlign: "top",
          background: "#F1F0EA",
        }}
      >
        {label}
      </th>
      <td
        style={{
          padding: "14px 24px 14px 16px",
          fontSize: 14,
          color: "#24302E",
          verticalAlign: "top",
          fontWeight: bold ? 700 : 400,
        }}
      >
        {children}
      </td>
    </tr>
  )
}
